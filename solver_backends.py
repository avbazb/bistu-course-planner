"""The same binary model is solved by either Gurobi or OR-Tools."""
import os
import re
import shutil
import subprocess
import tempfile
import time
from pathlib import Path


def warm_backend(backend):
    if backend=='ortools':
        from ortools.sat.python import cp_model
        return cp_model
    if backend!='gurobi':raise ValueError('未知求解器')


def solve_binary(variables, objective, constraints, backend):
    started=time.monotonic()
    if backend=='ortools':
        cp=warm_backend(backend)
        model=cp.CpModel()
        values={name:model.new_bool_var(name) for name in variables}
        # Only parse expressions generated by engine.py, never executable Python.
        for constraint in constraints:
            expression,relation,rhs=re.split(r'\s+(<=|>=|=)\s+',constraint.split(': ',1)[1])
            terms=[]
            for part in re.findall(r'[+-]?\s*[^+-]+',expression):
                match=re.fullmatch(r'\s*([+-]?)\s*(?:(\d+)\s+)?([A-Za-z0-9_]+)\s*',part)
                if not match:
                    if part.strip()=='0':continue
                    raise ValueError('内部模型表达式无效')
                sign,coefficient,name=match.groups()
                if name=='0':continue
                terms.append((-1 if sign=='-' else 1)*int(coefficient or 1)*values[name])
            lhs=sum(terms);right=int(rhs)
            model.add(lhs<=right if relation=='<=' else lhs>=right if relation=='>=' else lhs==right)
        model.minimize(sum(float(cost)*values[name] for cost,name in objective))
        solver=cp.CpSolver()
        solver.parameters.num_search_workers=1
        solver.parameters.random_seed=0
        status=solver.solve(model)
        if status==cp.INFEASIBLE:raise ValueError('当前固定班次存在冲突，无法排完；请调整班次或恢复自动')
        if status not in (cp.OPTIMAL,cp.FEASIBLE):raise RuntimeError('求解器未返回可行课表，保留原计划')
        return {name:float(solver.value(var)) for name,var in values.items()},status==cp.OPTIMAL,round((time.monotonic()-started)*1000)
    if backend!='gurobi':raise ValueError('未知求解器')
    executable=shutil.which('gurobi_cl') or shutil.which('gurobi_cl.exe')
    if not executable:raise RuntimeError('未找到 gurobi_cl，请安装 Gurobi、配置许可并加入 PATH')
    with tempfile.TemporaryDirectory(prefix='bistu_planner_') as folder:
        from engine import lp_expression
        model=Path(folder)/'schedule.lp';result=Path(folder)/'schedule.sol'
        model.write_text('\n'.join(['Minimize',' objective: '+lp_expression(objective),'Subject To',*constraints,'Bounds',*[f' 0 <= {v} <= 1' for v in variables],'Binary',*variables,'End']),encoding='ascii')
        completed=subprocess.run([executable,'Threads=1','MIPGap=0','LogFile=',f'ResultFile={result}',str(model)],capture_output=True,text=True,encoding='utf-8',errors='replace',cwd=folder,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
        log=(completed.stdout+'\n'+completed.stderr).lower()
        if 'infeasible' in log:raise ValueError('当前固定班次存在冲突，无法排完；请调整班次或恢复自动')
        if completed.returncode or not result.exists():raise RuntimeError('Gurobi 未返回课表，请检查许可证是否有效')
        values={}
        for line in result.read_text().splitlines():
            match=re.match(r'^\s*([A-Za-z0-9_]+)\s+([-+0-9.eE]+)',line)
            if match:values[match[1]]=float(match[2])
        if not values:raise RuntimeError('Gurobi 未返回可行课表')
        return values,'optimal solution found' in log,round((time.monotonic()-started)*1000)
